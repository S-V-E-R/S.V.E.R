-- 1. Setup categories become the picker's seven, plus OTHER for entries kept from before the picker.
--    Every existing item is kept with its name, note and link; the original category stays in legacy_category.
ALTER TABLE setup_items DROP CONSTRAINT setup_items_category_check;
ALTER TABLE setup_items
    ADD COLUMN legacy_category text,
    ADD COLUMN part_id text,
    ADD COLUMN submission_id text;
UPDATE setup_items SET legacy_category = category, category = CASE category
        WHEN 'MICROPHONE' THEN 'MIC'
        WHEN 'AUDIO_INTERFACE' THEN 'MIC'
        WHEN 'HEADPHONES' THEN 'PERIPHERALS'
        WHEN 'CAPTURE' THEN 'PERIPHERALS'
        WHEN 'MONITOR' THEN 'PERIPHERALS'
        WHEN 'KEYBOARD' THEN 'PERIPHERALS'
        WHEN 'MOUSE' THEN 'PERIPHERALS'
        WHEN 'CONTROLLER' THEN 'PERIPHERALS'
        WHEN 'PC' THEN 'OTHER'
        WHEN 'LIGHTING' THEN 'OTHER'
        ELSE category END
    WHERE category NOT IN ('CPU', 'GPU', 'CAMERA', 'OTHER');
ALTER TABLE setup_items ADD CONSTRAINT setup_items_category_check
    CHECK (category IN ('CPU', 'GPU', 'RAM', 'MOTHERBOARD', 'CAMERA', 'MIC', 'PERIPHERALS', 'OTHER'));

-- 2. The parts list. norm is brand + model, lowercased, '+' spelled "plus", other punctuation removed
--    (text::part_norm in the API). search adds a no-spaces form so "rtx4070" finds "RTX 4070".
CREATE TABLE parts (
    id text PRIMARY KEY,
    category text NOT NULL CHECK (category IN ('CPU', 'GPU', 'RAM', 'MOTHERBOARD', 'CAMERA', 'MIC', 'PERIPHERALS')),
    brand text NOT NULL,
    model text NOT NULL,
    norm text NOT NULL,
    search text GENERATED ALWAYS AS (norm || ' ' || replace(norm, ' ', '')) STORED,
    rank integer NOT NULL DEFAULT 1000,
    source text NOT NULL DEFAULT 'STAFF' CHECK (source IN ('SEED', 'STAFF')),
    status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'RETIRED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (category, norm)
);

-- 3. Custom entries waiting for staff review. One row per category and normalized name, ever:
--    later users typing the same thing share it, and a dismissed name is not queued again.
CREATE TABLE part_submissions (
    id text PRIMARY KEY,
    category text NOT NULL CHECK (category IN ('CPU', 'GPU', 'RAM', 'MOTHERBOARD', 'CAMERA', 'MIC', 'PERIPHERALS')),
    name text NOT NULL,
    norm text NOT NULL,
    submitted_by text REFERENCES users(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'DISMISSED')),
    part_id text REFERENCES parts(id),
    reviewed_by text REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (category, norm)
);
CREATE INDEX part_submissions_queue ON part_submissions (status, created_at);
CREATE INDEX part_submissions_by ON part_submissions (submitted_by, created_at);

ALTER TABLE setup_items
    ADD CONSTRAINT setup_items_part_fk FOREIGN KEY (part_id) REFERENCES parts(id) ON DELETE SET NULL,
    ADD CONSTRAINT setup_items_submission_fk FOREIGN KEY (submission_id) REFERENCES part_submissions(id) ON DELETE SET NULL;
CREATE INDEX setup_items_submission ON setup_items (submission_id) WHERE submission_id IS NOT NULL;

